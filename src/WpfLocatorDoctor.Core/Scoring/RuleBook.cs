namespace WpfLocatorDoctor.Core.Scoring;

/// <summary>A check that contributes to the score.</summary>
public sealed record CheckInfo(string Id, string Title, double Weight, string Question);

/// <summary>A kind of problem the tool reports.</summary>
public sealed record RuleInfo(string Id, string Title, string WhyItMatters);

/// <summary>Every check and rule, with plain-English explanations used in the reports.</summary>
public static class RuleBook
{
    public static readonly CheckInfo Coverage = new("coverage", "ID coverage", 30,
        "Of all the things a user can click, type into or select, how many have an AutomationId?");
    public static readonly CheckInfo Quality = new("quality", "ID quality", 15,
        "Were the IDs set on purpose, or borrowed from x:Name / x:Uid, or do they look machine-generated?");
    public static readonly CheckInfo Uniqueness = new("uniqueness", "Uniqueness and rows", 20,
        "Is each ID used only once per screen, and can the rows in each list be told apart?");
    public static readonly CheckInfo Stability = new("stability", "Stability", 15,
        "Are the IDs from the previous run (the baseline) still there?");
    public static readonly CheckInfo Visibility = new("visibility", "Visible to test tools", 10,
        "Can test tools actually see every control, or are some invisible (custom controls without automation support, empty drawn areas)?");
    public static readonly CheckInfo Names = new("names", "Readable names", 10,
        "Does every control have a readable label? (Helps tests and screen-reader users.)");

    public static readonly IReadOnlyList<CheckInfo> Checks = [Coverage, Quality, Uniqueness, Stability, Visibility, Names];

    public static readonly RuleInfo MissingId = new("WT001", "Control has no AutomationId",
        "Without an ID, tests must find the control by its text or position, which breaks when wording, language or layout changes.");
    public static readonly RuleInfo BorrowedFromXName = new("WT002", "ID is borrowed from x:Name",
        "WPF uses x:Name as a fallback ID. Developers rename x:Name freely without knowing a test depends on it.");
    public static readonly RuleInfo GeneratedLooking = new("WT003", "ID looks machine-generated",
        "IDs like \"Button_12\" or GUIDs are usually generated by tools and change when the screen is edited or rebuilt.");
    public static readonly RuleInfo Duplicate = new("WT004", "Same ID used more than once",
        "A test asking for this ID can't know which element it will get.");
    public static readonly RuleInfo RowsNotIdentifiable = new("WT005", "List rows can't be told apart",
        "Every row looks the same to a test, so it has to pick rows by position or text, which is fragile.");
    public static readonly RuleInfo InvisibleCustomControl = new("WT006", "Custom control is invisible to test tools",
        "The control's class doesn't create an automation peer, so UI Automation (and every test tool) can't see it or any ID set on it.");
    public static readonly RuleInfo IdOnInvisibleElement = new("WT007", "ID is set on an element test tools can't see",
        "This element type has no automation peer, so the ID goes nowhere. Its children are still visible.");
    public static readonly RuleInfo MissingName = new("WT008", "Control has no readable name",
        "Screen readers can't announce it, and tests can't fall back to finding it by label.");
    public static readonly RuleInfo BorrowedFromUid = new("WT009", "ID is borrowed from x:Uid",
        "x:Uid exists for translation tools, which may regenerate it. Set AutomationProperties.AutomationId instead.");
    public static readonly RuleInfo ChangedSinceBaseline = new("WT010", "ID disappeared since the baseline",
        "A test that used this ID will now fail.");
    public static readonly RuleInfo OpaqueElement = new("WT011", "Area that test tools can't look inside",
        "An empty custom/pane element with no ID, name or children. Often a drawn control (chart, canvas) that exposes nothing.");
    public static readonly RuleInfo MissingBehaviour = new("WT012", "Control doesn't support the expected action",
        "Test tools click buttons through the Invoke/Toggle behaviour. Without it, tests must fall back to mouse clicks.");

    public static readonly IReadOnlyList<RuleInfo> Rules =
    [
        MissingId, BorrowedFromXName, GeneratedLooking, Duplicate, RowsNotIdentifiable, InvisibleCustomControl,
        IdOnInvisibleElement, MissingName, BorrowedFromUid, ChangedSinceBaseline, OpaqueElement, MissingBehaviour,
    ];

    public static RuleInfo? FindRule(string id) => Rules.FirstOrDefault(r => r.Id == id);

    public static string GradeFor(double? score) => score switch
    {
        null => "N/A",
        >= 90 => "A",
        >= 75 => "B",
        >= 60 => "C",
        >= 40 => "D",
        _ => "F",
    };

    public static string GradeMeaning(string grade) => grade switch
    {
        "A" => "Easy to automate. Nearly every control has a stable, unique ID.",
        "B" => "Good. A few gaps to fix.",
        "C" => "Workable, but tests will need fragile workarounds in places.",
        "D" => "Hard to automate reliably. Many controls lack good IDs.",
        "F" => "Very hard to automate. Most controls can only be found by text or position.",
        _ => "Nothing to measure.",
    };
}
